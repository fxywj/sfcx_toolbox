function c = catalog()
%CATALOG Everything a front-end needs to populate its controls.
t = metricCatalog();
r = registry('list');
if ~isempty(r)
    extra = struct('id', {r.name}, ...
                   'family', {r.family}, ...
                   'label', {r.label}, ...
                   'label_zh', {r.label}, ...
                   'description', {r.description}, ...
                   'needs', repmat({'edges'}, 1, numel(r)));
    t = [t, extra];
end
c.metrics = t;
c.pipelines = struct( ...
    'id', {'pearson', 'precision'}, ...
    'description', {'Full correlation between regional BOLD series.', ...
                    'Partial correlation after Ledoit-Wolf shrinkage.'});
c.estimators = struct( ...
    'id', {'regional', 'node', 'edge'}, ...
    'description', {'SD across subjects of regional coupling c_i.', ...
                    'Mean over the edges a region carries of edge-level SD.', ...
                    'SD across subjects of a single edge.'});
c.scales = struct( ...
    'id', {'regional', 'network', 'edge', 'gap'}, ...
    'description', {'Regional summary.', 'Network summary.', ...
                    'Single edges.', 'Within-minus-between gap.'});
c.presets = struct( ...
    'id', {'default', 'edge-signal', 'node-contrast', 'precision-fingerprint'}, ...
    'metric', {'communicability', 'communicability', 'communicability', 'direct'}, ...
    'pipeline', {'pearson', 'pearson', 'pearson', 'precision'}, ...
    'estimator', {'regional', 'edge', 'node', 'regional'}, ...
    'scale', {'regional', 'edge', 'regional', 'regional'});
c.nulls = struct( ...
    'id', {'auto', 'spin', 'msr', 'permutation'}, ...
    'description', {'spin when coordinates are present, otherwise msr', ...
                    'spherical rotation; keeps spatial autocorrelation', ...
                    'Moran spectral randomisation; keeps autocorrelation', ...
                    'plain shuffle; smoke tests only'});
end
